`timescale 1ns / 1ps

/**
 * ============================================================================
 * Self-Checking Verilog Testbench for SHA-256 Hardware Accelerator
 * ============================================================================
 * Specification: docs/03_tb_spec.md
 * Target Simulator: Vivado Simulator (xsim) / Icarus Verilog
 *
 * Verification Architecture:
 * 1. Test Vector Ingestion:
 *    - Memory arrays load golden model outputs directly via `$readmemh`.
 *    - `input_vectors.txt`        -> 512-bit message blocks.
 *    - `intermediate_states.txt`  -> 256-bit {A,B,C,D,E,F,G,H} working variables.
 *    - `final_hashes.txt`         -> 256-bit expected final hash digests.
 *
 * 2. Clock & Reset:
 *    - 100MHz clock generation (10ns period, 50% duty cycle).
 *    - Synchronous active-high reset sequence over 5 clock cycles.
 *
 * 3. Verification State Machine:
 *    - Feeds 512-bit message blocks with single-cycle `valid_in` pulse.
 *    - Performs cycle-by-cycle assertions during all 64 compression rounds,
 *      comparing DUT `intermediate_state_out` against `expected_intermediate_mem`.
 *    - Halts gracefully on first mismatch via `$stop` with an A-H breakdown.
 *    - Verifies final digest on `valid_out` assertion against `expected_final_mem`.
 * ============================================================================
 */

module tb_sha256;

    // ------------------------------------------------------------------------
    // Timing and Architecture Parameters
    // ------------------------------------------------------------------------
    parameter CLK_PERIOD   = 10;    // 10ns clock period = 100MHz
    parameter MAX_BLOCKS   = 1;     // Number of 512-bit blocks to verify
    parameter TOTAL_ROUNDS = 64;    // 64 compression rounds per block

    // ------------------------------------------------------------------------
    // Device Under Test (DUT) Interface Signals
    // ------------------------------------------------------------------------
    reg          clk;                     // 100MHz system clock
    reg          rst;                     // Synchronous active-high reset
    reg          valid_in;                // Block input valid handshake pulse
    reg  [511:0] block_in;                // 512-bit message block

    wire [5:0]   round_out;               // Current round counter [0..63]
    wire [255:0] intermediate_state_out;  // Concatenated {A,B,C,D,E,F,G,H} registers
    wire [255:0] hash_out;                // Final 256-bit computed hash digest
    wire         valid_out;               // High for 1 cycle when hash_out is valid

    // ------------------------------------------------------------------------
    // Golden Reference Verification Memories (Loaded via $readmemh)
    // ------------------------------------------------------------------------
    reg [511:0] input_mem                 [0:MAX_BLOCKS-1];
    reg [255:0] expected_intermediate_mem [0:(MAX_BLOCKS * TOTAL_ROUNDS)-1];
    reg [255:0] expected_final_mem        [0:MAX_BLOCKS-1];

    sha256_core u_dut (
        .clk                   (clk),
        .rst                   (rst),
        .valid_in              (valid_in),
        .block_in              (block_in),
        .round_out             (round_out),
        .intermediate_state_out(intermediate_state_out),
        .hash_out              (hash_out),
        .valid_out             (valid_out)
    );

    initial begin
        clk = 1'b0;
        forever #(CLK_PERIOD / 2) clk = ~clk;
    end

    initial begin
        #100000;
        $display("\n[FATAL ERROR] Simulation watchdog timeout reached (100us)!");
        $stop;
    end

    initial begin
        $display("================================================================");
        $display(" SHA-256 Accelerator Hardware Verification Testbench");
        $display(" Target: 100MHz clock, Self-Checking cycle-by-cycle assertions");
        $display("================================================================");
        $display("[INFO] Loading golden vectors generated by C++ reference model...");

        $readmemh("C:/Users/Purav/Desktop/Major Project/golden_model/input_vectors.txt", input_mem);
        $display("  [LOAD] C:/Users/Purav/Desktop/Major Project/golden_model/input_vectors.txt       -> input_mem (512-bit blocks)");

        $readmemh("C:/Users/Purav/Desktop/Major Project/golden_model/intermediate_states.txt", expected_intermediate_mem);
        $display("  [LOAD] C:/Users/Purav/Desktop/Major Project/golden_model/intermediate_states.txt -> expected_intermediate_mem (256-bit states)");

        $readmemh("C:/Users/Purav/Desktop/Major Project/golden_model/final_hashes.txt", expected_final_mem);
        $display("  [LOAD] C:/Users/Purav/Desktop/Major Project/golden_model/final_hashes.txt        -> expected_final_mem (256-bit digests)");

        $display("[INFO] All test vector memories initialized successfully.");
        $display("================================================================\n");
    end

    integer block_idx;
    integer round_idx;
    reg [255:0] exp_round_state;
    reg [255:0] exp_final_hash;

    initial begin
        $dumpfile("tb_sha256.vcd");
        $dumpvars(0, tb_sha256);

        rst      = 1'b0;
        valid_in = 1'b0;
        block_in = 512'd0;

        $display("[TIME: %0t ns] Applying synchronous active-high reset...", $time);
        @(posedge clk);
        rst <= 1'b1;
        repeat (5) @(posedge clk);
        rst <= 1'b0;
        $display("[TIME: %0t ns] Reset released. Initializing block transmission...", $time);
        repeat (2) @(posedge clk);

        for (block_idx = 0; block_idx < MAX_BLOCKS; block_idx = block_idx + 1) begin
            $display("----------------------------------------------------------------");
            $display("[BLOCK %0d/%0d] Injecting 512-bit message block...", block_idx + 1, MAX_BLOCKS);
            $display("  Block Data: %0128h", input_mem[block_idx]);
            $display("----------------------------------------------------------------");

            @(posedge clk);
            block_in <= input_mem[block_idx];
            valid_in <= 1'b1;

            @(posedge clk);
            valid_in <= 1'b0;
            block_in <= 512'd0;

            for (round_idx = 0; round_idx < TOTAL_ROUNDS; round_idx = round_idx + 1) begin
                #1;
                while (round_out !== round_idx[5:0]) begin
                    @(posedge clk);
                    #1;
                end

                exp_round_state = expected_intermediate_mem[block_idx * TOTAL_ROUNDS + round_idx];

                if (intermediate_state_out !== exp_round_state) begin
                    $display("\n****************************************************************");
                    $display("  [ASSERTION FAILED] Round State Mismatch!");
                    $display("  Time        : %0t ns", $time);
                    $display("  Block Index : %0d", block_idx);
                    $display("  Round       : %0d", round_idx);
                    $display("  Expected    : 0x%064h", exp_round_state);
                    $display("  Actual      : 0x%064h", intermediate_state_out);
                    $display("  --------------------------------------------------------------");
                    $display("  Working Variables Breakdown (Expected vs Actual):");
                    $display("    A: %08h vs %08h  %s", exp_round_state[255:224], intermediate_state_out[255:224], (exp_round_state[255:224] == intermediate_state_out[255:224] ? "[PASS]" : "[MISMATCH]"));
                    $display("    B: %08h vs %08h  %s", exp_round_state[223:192], intermediate_state_out[223:192], (exp_round_state[223:192] == intermediate_state_out[223:192] ? "[PASS]" : "[MISMATCH]"));
                    $display("    C: %08h vs %08h  %s", exp_round_state[191:160], intermediate_state_out[191:160], (exp_round_state[191:160] == intermediate_state_out[191:160] ? "[PASS]" : "[MISMATCH]"));
                    $display("    D: %08h vs %08h  %s", exp_round_state[159:128], intermediate_state_out[159:128], (exp_round_state[159:128] == intermediate_state_out[159:128] ? "[PASS]" : "[MISMATCH]"));
                    $display("    E: %08h vs %08h  %s", exp_round_state[127:96],  intermediate_state_out[127:96],  (exp_round_state[127:96]  == intermediate_state_out[127:96]  ? "[PASS]" : "[MISMATCH]"));
                    $display("    F: %08h vs %08h  %s", exp_round_state[95:64],   intermediate_state_out[95:64],   (exp_round_state[95:64]   == intermediate_state_out[95:64]   ? "[PASS]" : "[MISMATCH]"));
                    $display("    G: %08h vs %08h  %s", exp_round_state[63:32],   intermediate_state_out[63:32],   (exp_round_state[63:32]   == intermediate_state_out[63:32]   ? "[PASS]" : "[MISMATCH]"));
                    $display("    H: %08h vs %08h  %s", exp_round_state[31:0],    intermediate_state_out[31:0],    (exp_round_state[31:0]    == intermediate_state_out[31:0]    ? "[PASS]" : "[MISMATCH]"));
                    $display("****************************************************************\n");
                    $stop;
                end else begin
                    $display("  [MATCH] Round %2d State: %064h", round_idx, intermediate_state_out);
                end

                @(posedge clk);
            end

            #1;
            while (!valid_out) begin
                @(posedge clk);
                #1;
            end

            exp_final_hash = expected_final_mem[block_idx];

            if (hash_out !== exp_final_hash) begin
                $display("\n****************************************************************");
                $display("  [ASSERTION FAILED] Final Hash Digest Mismatch!");
                $display("  Time        : %0t ns", $time);
                $display("  Block Index : %0d", block_idx);
                $display("  Expected    : 0x%064h", exp_final_hash);
                $display("  Actual      : 0x%064h", hash_out);
                $display("****************************************************************\n");
                $stop;
            end else begin
                $display("\n  [VERIFIED] Block %0d Final Hash: %064h\n", block_idx + 1, hash_out);
            end

            repeat (3) @(posedge clk);
        end

        $display("================================================================");
        $display("                   SIMULATION PASSED");
        $display(" Verified %0d block(s) and %0d rounds against Golden Model",
                 MAX_BLOCKS, MAX_BLOCKS * TOTAL_ROUNDS);
        $display(" Final Digest Output: %064h", hash_out);
        $display("================================================================\n");

        $finish;
    end

endmodule
