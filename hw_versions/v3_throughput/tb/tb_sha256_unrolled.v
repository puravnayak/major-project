`timescale 1ns / 1ps

/**
 * ============================================================================
 * Module: tb_sha256_unrolled
 * Description: Self-Checking Testbench for SHA-256 v3.0 2x Unrolled Architecture.
 *              Evaluates 32 unrolled execution cycles per 512-bit message block,
 *              asserting intermediate working state registers against the 32
 *              unrolled golden reference states (saved at the end of each
 *              2-round pair: rounds 1, 3, 5, ..., 63).
 * Specification: docs/08_v3_throughput_architecture.md
 * ============================================================================
 */

module tb_sha256_unrolled;

    // ------------------------------------------------------------------------
    // Timing and Architecture Parameters
    // ------------------------------------------------------------------------
    parameter CLK_PERIOD       = 10;   // 10ns clock period
    parameter MAX_BLOCKS       = 1;    // Number of 512-bit blocks to verify
    parameter CYCLES_PER_BLOCK = 32;   // 32 unrolled clock cycles per 512-bit block

    // ------------------------------------------------------------------------
    // Device Under Test (DUT) Interface Signals
    // ------------------------------------------------------------------------
    reg          clk;                     // System clock
    reg          rst;                     // Synchronous active-high reset
    reg          valid_in;                // Block input valid handshake pulse
    reg  [511:0] block_in;                // 512-bit message block

    wire [5:0]   round_out;               // Active round/step index
    wire [255:0] intermediate_state_out;  // Working state {A,B,C,D,E,F,G,H}
    wire [255:0] hash_out;                // Final 256-bit computed hash digest
    wire         valid_out;               // High for 1 cycle when hash_out is valid

    // expected_intermediate_mem holds all 64 rounds per block, sampled at unrolled boundaries
    parameter TOTAL_ROUNDS = 64;
    reg [511:0] input_mem                 [0:MAX_BLOCKS-1];
    reg [255:0] expected_intermediate_mem [0:(MAX_BLOCKS * TOTAL_ROUNDS)-1];
    reg [255:0] expected_final_mem        [0:MAX_BLOCKS-1];

    // ------------------------------------------------------------------------
    // Instantiate v3.0 2x Unrolled sha256_top DUT
    // ------------------------------------------------------------------------
    sha256_top u_dut (
        .clk                    (clk),
        .rst                    (rst),
        .valid_in               (valid_in),
        .block_in               (block_in),
        .round_out              (round_out),
        .intermediate_state_out (intermediate_state_out),
        .hash_out               (hash_out),
        .valid_out              (valid_out)
    );

    // ------------------------------------------------------------------------
    // Clock Generation
    // ------------------------------------------------------------------------
    initial begin
        clk = 1'b0;
        forever #(CLK_PERIOD / 2) clk = ~clk;
    end

    // ------------------------------------------------------------------------
    // Watchdog Timer (Safety circuit to prevent infinite simulation loops)
    // ------------------------------------------------------------------------
    initial begin
        #100000;
        $display("\n[FATAL ERROR] Simulation watchdog timeout reached (100us)!");
        $stop;
    end

    // ------------------------------------------------------------------------
    // Load Verification Test Vectors via $readmemh
    // ------------------------------------------------------------------------
    initial begin
        $display("================================================================");
        $display(" SHA-256 v3.0 2x Unrolled Hardware Verification Testbench");
        $display(" Target: 32 Unrolled Cycles/Block, Cycle-by-Cycle Assertions");
        $display("================================================================");
        $display("[INFO] Loading golden vectors generated by C++ reference model...");

        $readmemh("C:/Users/Purav/Desktop/Major Project/golden_model/input_vectors.txt", input_mem);
        $display("  [LOAD] C:/Users/Purav/Desktop/Major Project/golden_model/input_vectors.txt       -> input_mem (512-bit blocks)");

        $readmemh("C:/Users/Purav/Desktop/Major Project/golden_model/intermediate_states.txt", expected_intermediate_mem);
        $display("  [LOAD] C:/Users/Purav/Desktop/Major Project/golden_model/intermediate_states.txt -> expected_intermediate_mem (32 states/block)");

        $readmemh("C:/Users/Purav/Desktop/Major Project/golden_model/final_hashes.txt", expected_final_mem);
        $display("  [LOAD] C:/Users/Purav/Desktop/Major Project/golden_model/final_hashes.txt        -> expected_final_mem (256-bit digests)");

        $display("[INFO] All test vector memories initialized successfully.");
        $display("================================================================\n");
    end

    // ------------------------------------------------------------------------
    // Stimulus and Self-Checking Cycle-by-Cycle Verification Process
    // ------------------------------------------------------------------------
    integer block_idx;
    integer cycle_idx;
    reg [255:0] exp_cycle_state;
    reg [255:0] exp_final_hash;

    initial begin
        $dumpfile("tb_sha256_unrolled.vcd");
        $dumpvars(0, tb_sha256_unrolled);

        rst      = 1'b0;
        valid_in = 1'b0;
        block_in = 512'd0;

        $display("[TIME: %0t ns] Applying synchronous active-high reset...", $time);
        @(posedge clk);
        rst <= 1'b1;
        repeat (5) @(posedge clk);
        rst <= 1'b0;
        $display("[TIME: %0t ns] Reset released. Initializing block transmission...", $time);
        repeat (2) @(posedge clk);

        for (block_idx = 0; block_idx < MAX_BLOCKS; block_idx = block_idx + 1) begin
            $display("----------------------------------------------------------------");
            $display("[BLOCK %0d/%0d] Injecting 512-bit message block...", block_idx + 1, MAX_BLOCKS);
            $display("  Block Data: %0128h", input_mem[block_idx]);
            $display("----------------------------------------------------------------");

            @(posedge clk);
            block_in <= input_mem[block_idx];
            valid_in <= 1'b1;

            @(posedge clk);
            valid_in <= 1'b0;
            block_in <= 512'd0;

            // ----------------------------------------------------------------
            // 32-Cycle Unrolled Compression Verification Loop (cycles 0..31)
            // ----------------------------------------------------------------
            for (cycle_idx = 0; cycle_idx < CYCLES_PER_BLOCK; cycle_idx = cycle_idx + 1) begin
                #1;
                // Wait for the DUT to enter and advance to the specific unrolled cycle
                while (round_out !== (cycle_idx * 2 + 1) && round_out !== cycle_idx[5:0]) begin
                    @(posedge clk);
                    #1;
                end

                exp_cycle_state = expected_intermediate_mem[block_idx * TOTAL_ROUNDS + (cycle_idx * 2 + 1)];

                if (intermediate_state_out !== exp_cycle_state) begin
                    $display("\n****************************************************************");
                    $display("  [ASSERTION FAILED] Unrolled State Mismatch!");
                    $display("  Time        : %0t ns", $time);
                    $display("  Block Index : %0d", block_idx);
                    $display("  Cycle Index : %0d (Rounds %0d & %0d)", cycle_idx, cycle_idx * 2, cycle_idx * 2 + 1);
                    $display("  Expected    : 0x%064h", exp_cycle_state);
                    $display("  Actual      : 0x%064h", intermediate_state_out);
                    $display("  --------------------------------------------------------------");
                    $display("  Working Variables Breakdown (Expected vs Actual):");
                    $display("    A: %08h vs %08h  %s", exp_cycle_state[255:224], intermediate_state_out[255:224], (exp_cycle_state[255:224] == intermediate_state_out[255:224] ? "[PASS]" : "[MISMATCH]"));
                    $display("    B: %08h vs %08h  %s", exp_cycle_state[223:192], intermediate_state_out[223:192], (exp_cycle_state[223:192] == intermediate_state_out[223:192] ? "[PASS]" : "[MISMATCH]"));
                    $display("    C: %08h vs %08h  %s", exp_cycle_state[191:160], intermediate_state_out[191:160], (exp_cycle_state[191:160] == intermediate_state_out[191:160] ? "[PASS]" : "[MISMATCH]"));
                    $display("    D: %08h vs %08h  %s", exp_cycle_state[159:128], intermediate_state_out[159:128], (exp_cycle_state[159:128] == intermediate_state_out[159:128] ? "[PASS]" : "[MISMATCH]"));
                    $display("    E: %08h vs %08h  %s", exp_cycle_state[127:96],  intermediate_state_out[127:96],  (exp_cycle_state[127:96]  == intermediate_state_out[127:96]  ? "[PASS]" : "[MISMATCH]"));
                    $display("    F: %08h vs %08h  %s", exp_cycle_state[95:64],   intermediate_state_out[95:64],   (exp_cycle_state[95:64]   == intermediate_state_out[95:64]   ? "[PASS]" : "[MISMATCH]"));
                    $display("    G: %08h vs %08h  %s", exp_cycle_state[63:32],   intermediate_state_out[63:32],   (exp_cycle_state[63:32]   == intermediate_state_out[63:32]   ? "[PASS]" : "[MISMATCH]"));
                    $display("    H: %08h vs %08h  %s", exp_cycle_state[31:0],    intermediate_state_out[31:0],    (exp_cycle_state[31:0]    == intermediate_state_out[31:0]    ? "[PASS]" : "[MISMATCH]"));
                    $display("****************************************************************\n");
                    $stop;
                end else begin
                    $display("  [MATCH] Cycle %2d (Rounds %2d-%2d) State: %064h", cycle_idx, cycle_idx * 2, cycle_idx * 2 + 1, intermediate_state_out);
                end

                @(posedge clk);
            end

            // ----------------------------------------------------------------
            // Final Hash Digest Verification
            // ----------------------------------------------------------------
            #1;
            while (!valid_out) begin
                @(posedge clk);
                #1;
            end

            exp_final_hash = expected_final_mem[block_idx];

            if (hash_out !== exp_final_hash) begin
                $display("\n****************************************************************");
                $display("  [ASSERTION FAILED] Final Digest Mismatch!");
                $display("  Block Index : %0d", block_idx);
                $display("  Expected    : 0x%064h", exp_final_hash);
                $display("  Actual      : 0x%064h", hash_out);
                $display("****************************************************************\n");
                $stop;
            end else begin
                $display("\n  [VERIFIED] Block %0d Final Hash: %064h", block_idx + 1, hash_out);
            end
        end

        $display("\n================================================================");
        $display("                   SIMULATION PASSED");
        $display(" Verified %0d block(s) and %0d unrolled cycle(s) against Golden Model", MAX_BLOCKS, MAX_BLOCKS * CYCLES_PER_BLOCK);
        $display(" Final Digest Output: %064h", hash_out);
        $display("================================================================\n");

        repeat (5) @(posedge clk);
        $finish;
    end

endmodule
