`timescale 1ns / 1ps

/**
 * ============================================================================
 * Module: tb_sha256_multicore
 * Description: Self-Checking Testbench for SHA-256 v4.0 Dual-Core Architecture.
 *              Feeds two distinct 512-bit message blocks simultaneously to Core 0
 *              and Core 1, and independently verifies both 256-bit hash digests.
 * Specification: docs/09_v4_multicore_architecture.md
 * ============================================================================
 */

module tb_sha256_multicore;

    // ------------------------------------------------------------------------
    // Timing and Architecture Parameters
    // ------------------------------------------------------------------------
    parameter CLK_PERIOD       = 10;   // 10ns clock period = 100MHz
    parameter TOTAL_BLOCKS     = 2;    // Dual-core feeds 2 blocks simultaneously

    // ------------------------------------------------------------------------
    // DUT Interface Signals
    // ------------------------------------------------------------------------
    reg          clk;
    reg          rst;
    reg          valid_in;
    reg  [511:0] block_in_0;
    reg  [511:0] block_in_1;

    wire [5:0]   round_out_0;
    wire [5:0]   round_out_1;
    wire [255:0] intermediate_out_0;
    wire [255:0] intermediate_out_1;
    wire [255:0] hash_out_0;
    wire [255:0] hash_out_1;
    wire         valid_out_0;
    wire         valid_out_1;

    // ------------------------------------------------------------------------
    // Golden Reference Verification Memories (Loaded via $readmemh)
    // ------------------------------------------------------------------------
    reg [511:0] input_mem          [0:TOTAL_BLOCKS-1];
    reg [255:0] expected_final_mem [0:TOTAL_BLOCKS-1];

    // ------------------------------------------------------------------------
    // Instantiate Dual-Core Top DUT
    // ------------------------------------------------------------------------
    sha256_multicore_top u_dut (
        .clk                (clk),
        .rst                (rst),
        .valid_in           (valid_in),
        .block_in_0         (block_in_0),
        .block_in_1         (block_in_1),
        .round_out_0        (round_out_0),
        .round_out_1        (round_out_1),
        .intermediate_out_0 (intermediate_out_0),
        .intermediate_out_1 (intermediate_out_1),
        .hash_out_0         (hash_out_0),
        .hash_out_1         (hash_out_1),
        .valid_out_0        (valid_out_0),
        .valid_out_1        (valid_out_1)
    );

    // ------------------------------------------------------------------------
    // Clock Generation
    // ------------------------------------------------------------------------
    initial begin
        clk = 1'b0;
        forever #(CLK_PERIOD / 2) clk = ~clk;
    end

    // ------------------------------------------------------------------------
    // Watchdog Timer
    // ------------------------------------------------------------------------
    initial begin
        #100000;
        $display("\n[FATAL ERROR] Simulation watchdog timeout reached (100us)!");
        $stop;
    end

    // ------------------------------------------------------------------------
    // Verification Vector Loading
    // ------------------------------------------------------------------------
    initial begin
        $display("================================================================");
        $display(" SHA-256 v4.0 Dual-Core Hardware Verification Testbench");
        $display(" Target: Parallel Dual-Stream Verification (Core 0 & Core 1)");
        $display("================================================================");
        $display("[INFO] Loading golden vectors generated by C++ reference model...");

        $readmemh("C:/Users/Purav/Desktop/Major Project/golden_model/input_vectors.txt", input_mem);
        $display("  [LOAD] C:/Users/Purav/Desktop/Major Project/golden_model/input_vectors.txt -> input_mem (Dual Blocks)");

        $readmemh("C:/Users/Purav/Desktop/Major Project/golden_model/final_hashes.txt", expected_final_mem);
        $display("  [LOAD] C:/Users/Purav/Desktop/Major Project/golden_model/final_hashes.txt  -> expected_final_mem (Dual Digests)");

        $display("[INFO] Verification memories initialized successfully.");
        $display("================================================================\n");
    end

    // ------------------------------------------------------------------------
    // Verification Sequence
    // ------------------------------------------------------------------------
    reg [255:0] exp_hash_0;
    reg [255:0] exp_hash_1;
    reg core_0_passed;
    reg core_1_passed;

    initial begin
        $dumpfile("tb_sha256_multicore.vcd");
        $dumpvars(0, tb_sha256_multicore);

        rst        = 1'b0;
        valid_in   = 1'b0;
        block_in_0 = 512'd0;
        block_in_1 = 512'd0;
        core_0_passed = 1'b0;
        core_1_passed = 1'b0;

        $display("[TIME: %0t ns] Applying synchronous active-high reset...", $time);
        @(posedge clk);
        rst <= 1'b1;
        repeat (5) @(posedge clk);
        rst <= 1'b0;
        $display("[TIME: %0t ns] Reset released. Initializing dual-core transmission...", $time);
        repeat (2) @(posedge clk);

        $display("----------------------------------------------------------------");
        $display("[DUAL DISPATCH] Feeding Block 0 to Core 0 and Block 1 to Core 1...");
        $display("  Core 0 Block [N=0]  : %0128h", input_mem[0]);
        $display("  Core 1 Block [N=1]  : %0128h", input_mem[1]);
        $display("----------------------------------------------------------------");

        @(posedge clk);
        block_in_0 <= input_mem[0];
        block_in_1 <= input_mem[1];
        valid_in   <= 1'b1;

        @(posedge clk);
        valid_in   <= 1'b0;
        block_in_0 <= 512'd0;
        block_in_1 <= 512'd0;

        // Monitor outputs from both cores
        fork
            begin : monitor_core_0
                #1;
                while (!valid_out_0) begin
                    @(posedge clk);
                    #1;
                end
                exp_hash_0 = expected_final_mem[0];
                if (hash_out_0 !== exp_hash_0) begin
                    $display("\n[ERROR] Core 0 Hash Mismatch!");
                    $display("  Expected : 0x%064h", exp_hash_0);
                    $display("  Actual   : 0x%064h", hash_out_0);
                    $stop;
                end else begin
                    $display("  [VERIFIED Core 0] Output Hash: %064h", hash_out_0);
                    core_0_passed = 1'b1;
                end
            end

            begin : monitor_core_1
                #1;
                while (!valid_out_1) begin
                    @(posedge clk);
                    #1;
                end
                exp_hash_1 = expected_final_mem[1];
                if (hash_out_1 !== exp_hash_1) begin
                    $display("\n[ERROR] Core 1 Hash Mismatch!");
                    $display("  Expected : 0x%064h", exp_hash_1);
                    $display("  Actual   : 0x%064h", hash_out_1);
                    $stop;
                end else begin
                    $display("  [VERIFIED Core 1] Output Hash: %064h", hash_out_1);
                    core_1_passed = 1'b1;
                end
            end
        join

        if (core_0_passed && core_1_passed) begin
            $display("\n================================================================");
            $display("                   SIMULATION PASSED");
            $display(" Dual-Core Parallel SHA-256 Accelerators Verified Successfully!");
            $display(" Core 0 Digest: %064h", hash_out_0);
            $display(" Core 1 Digest: %064h", hash_out_1);
            $display("================================================================\n");
        end

        repeat (5) @(posedge clk);
        $finish;
    end

endmodule
