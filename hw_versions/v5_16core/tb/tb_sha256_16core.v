`timescale 1ns / 1ps

/**
 * ============================================================================
 * Module: tb_sha256_16core
 * Description: Self-Checking Testbench for SHA-256 v5.0 16-Core Mega-Array.
 *              Simultaneously feeds 16 sequential 512-bit message blocks
 *              (8192 bits total) into the flattened [8191:0] input bus, and
 *              concurrently verifies all 16 256-bit hash digests [4095:0]
 *              against golden reference vectors.
 * Specification: docs/10_v5_16core_architecture.md
 * ============================================================================
 */

module tb_sha256_16core;

    // ------------------------------------------------------------------------
    // Timing and Architecture Parameters
    // ------------------------------------------------------------------------
    parameter CLK_PERIOD   = 10;   // 10ns clock period = 100MHz
    parameter NUM_CORES    = 16;   // 16 parallel processing engines

    // ------------------------------------------------------------------------
    // DUT Interface Signals
    // ------------------------------------------------------------------------
    reg           clk;
    reg           rst;
    reg           valid_in;
    reg  [8191:0] block_in;

    wire [4095:0] hash_out;
    wire [15:0]   valid_out_bus;

    // ------------------------------------------------------------------------
    // Golden Reference Verification Memories (Loaded via $readmemh)
    // ------------------------------------------------------------------------
    reg [511:0] input_mem          [0:NUM_CORES-1];
    reg [255:0] expected_final_mem [0:NUM_CORES-1];

    // ------------------------------------------------------------------------
    // Instantiate 16-Core Top DUT
    // ------------------------------------------------------------------------
    sha256_16core_top u_dut (
        .clk           (clk),
        .rst           (rst),
        .valid_in      (valid_in),
        .block_in      (block_in),
        .hash_out      (hash_out),
        .valid_out_bus (valid_out_bus)
    );

    // ------------------------------------------------------------------------
    // Clock Generation
    // ------------------------------------------------------------------------
    initial begin
        clk = 1'b0;
        forever #(CLK_PERIOD / 2) clk = ~clk;
    end

    // ------------------------------------------------------------------------
    // Watchdog Timer
    // ------------------------------------------------------------------------
    initial begin
        #150000;
        $display("\n[FATAL ERROR] Simulation watchdog timeout reached (150us)!");
        $stop;
    end

    // ------------------------------------------------------------------------
    // Verification Vector Loading
    // ------------------------------------------------------------------------
    integer load_idx;
    initial begin
        $display("================================================================");
        $display(" SHA-256 v5.0 16-Core Mega-Array Verification Testbench");
        $display(" Target: 16 Parallel Streams, 8192 bits/batch, 33 Cycles");
        $display("================================================================");
        $display("[INFO] Loading golden vectors generated by C++ reference model...");

        $readmemh("C:/Users/Purav/Desktop/Major Project/golden_model/input_vectors.txt", input_mem);
        if (input_mem[0] === 512'bx) begin
            $readmemh("../golden_model/input_vectors.txt", input_mem);
        end
        if (input_mem[0] === 512'bx) begin
            $readmemh("golden_model/input_vectors.txt", input_mem);
        end
        $display("  [LOAD] C:/Users/Purav/Desktop/Major Project/golden_model/input_vectors.txt -> input_mem (16 blocks)");

        $readmemh("C:/Users/Purav/Desktop/Major Project/golden_model/final_hashes.txt", expected_final_mem);
        if (expected_final_mem[0] === 256'bx) begin
            $readmemh("../golden_model/final_hashes.txt", expected_final_mem);
        end
        if (expected_final_mem[0] === 256'bx) begin
            $readmemh("golden_model/final_hashes.txt", expected_final_mem);
        end
        $display("  [LOAD] C:/Users/Purav/Desktop/Major Project/golden_model/final_hashes.txt  -> expected_final_mem (16 digests)");

        $display("[INFO] Verification memories initialized successfully.");
        $display("================================================================\n");
    end

    // ------------------------------------------------------------------------
    // Stimulus and Verification Sequence
    // ------------------------------------------------------------------------
    integer k;
    integer pass_count;

    initial begin
        $dumpfile("tb_sha256_16core.vcd");
        $dumpvars(0, tb_sha256_16core);

        rst        = 1'b0;
        valid_in   = 1'b0;
        block_in   = 8192'd0;
        pass_count = 0;

        $display("[TIME: %0t ns] Applying synchronous active-high reset...", $time);
        @(posedge clk);
        rst <= 1'b1;
        repeat (5) @(posedge clk);
        rst <= 1'b0;
        $display("[TIME: %0t ns] Reset released. Dispatching 16 blocks to mega-array...", $time);
        repeat (2) @(posedge clk);

        // Pack 16 blocks into flattened [8191:0] bus
        for (k = 0; k < NUM_CORES; k = k + 1) begin
            block_in[k*512 +: 512] = input_mem[k];
            $display("  Core %2d Block: %064h...", k, input_mem[k][511:256]);
        end

        @(posedge clk);
        valid_in <= 1'b1;

        @(posedge clk);
        valid_in <= 1'b0;
        block_in <= 8192'd0;

        // Await simultaneous completion across all 16 cores
        $display("[TIME: %0t ns] Processing 16 parallel blocks (33 cycles)...", $time);
        #1;
        while (valid_out_bus !== 16'hFFFF) begin
            @(posedge clk);
            #1;
        end

        $display("[TIME: %0t ns] Output ready strobe asserted (valid_out_bus = 0x%04h). Verifying digests...", $time, valid_out_bus);

        // Verify each computed digest against golden model
        for (k = 0; k < NUM_CORES; k = k + 1) begin
            if (hash_out[k*256 +: 256] !== expected_final_mem[k]) begin
                $display("\n****************************************************************");
                $display("  [ASSERTION FAILED] Core %2d Digest Mismatch!", k);
                $display("  Time     : %0t ns", $time);
                $display("  Expected : 0x%064h", expected_final_mem[k]);
                $display("  Actual   : 0x%064h", hash_out[k*256 +: 256]);
                $display("****************************************************************\n");
                $stop;
            end else begin
                $display("  [VERIFIED Core %2d] Digest: %064h", k, hash_out[k*256 +: 256]);
                pass_count = pass_count + 1;
            end
        end

        if (pass_count == NUM_CORES) begin
            $display("\n================================================================");
            $display("                   SIMULATION PASSED");
            $display(" 16-Core Mega-Array Verified Successfully! (16/16 Digests Match)");
            $display(" Total Concurrently Processed: 8,192 bits (1,024 Bytes)");
            $display("================================================================\n");
        end

        repeat (5) @(posedge clk);
        $finish;
    end

endmodule
