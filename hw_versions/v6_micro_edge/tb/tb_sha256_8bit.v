`timescale 1ns / 1ps

/**
 * ============================================================================
 * Module: tb_sha256_8bit
 * Description: Self-Checking Testbench for SHA-256 v6.0 Micro-Edge 8-bit Folded
 *              Architecture. Feeds a standard 512-bit NIST block, monitors the
 *              256-cycle COMPRESS execution phase, and verifies the final
 *              256-bit hash digest on valid_out assertion.
 * Specification: docs/11_v6_micro_edge_architecture.md
 * ============================================================================
 */

module tb_sha256_8bit;

    // ------------------------------------------------------------------------
    // Timing and Architecture Parameters
    // ------------------------------------------------------------------------
    parameter CLK_PERIOD = 100;   // 100ns clock period = 10MHz IoT clock

    // ------------------------------------------------------------------------
    // DUT Interface Signals
    // ------------------------------------------------------------------------
    reg          clk;
    reg          rst;
    reg          valid_in;
    reg  [511:0] block_in;

    wire [5:0]   round_out;
    wire [255:0] intermediate_state_out;
    wire [255:0] hash_out;
    wire         valid_out;

    // ------------------------------------------------------------------------
    // Golden Reference Verification Memories
    // ------------------------------------------------------------------------
    reg [511:0] input_mem          [0:0];
    reg [255:0] expected_final_mem [0:0];

    // ------------------------------------------------------------------------
    // Instantiate 8-Bit Folded Top DUT
    // ------------------------------------------------------------------------
    sha256_top_8bit u_dut (
        .clk                    (clk),
        .rst                    (rst),
        .valid_in               (valid_in),
        .block_in               (block_in),
        .round_out              (round_out),
        .intermediate_state_out (intermediate_state_out),
        .hash_out               (hash_out),
        .valid_out              (valid_out)
    );

    // ------------------------------------------------------------------------
    // Clock Generation (10 MHz)
    // ------------------------------------------------------------------------
    initial begin
        clk = 1'b0;
        forever #(CLK_PERIOD / 2) clk = ~clk;
    end

    // ------------------------------------------------------------------------
    // Watchdog Timer (300us)
    // ------------------------------------------------------------------------
    initial begin
        #300000;
        $display("\n[FATAL ERROR] Simulation watchdog timeout reached (300us)!");
        $stop;
    end

    // ------------------------------------------------------------------------
    // Load Verification Vectors
    // ------------------------------------------------------------------------
    initial begin
        $display("================================================================");
        $display(" SHA-256 v6.0 Micro-Edge 8-Bit Folded Hardware Testbench");
        $display(" Target: 10MHz Clock, 256 Compression Cycles per Block");
        $display("================================================================");
        $display("[INFO] Loading golden vectors generated by C++ reference model...");

        $readmemh("C:/Users/Purav/Desktop/Major Project/golden_model/input_vectors.txt", input_mem);
        if (input_mem[0] === 512'bx) begin
            $readmemh("../golden_model/input_vectors.txt", input_mem);
        end
        if (input_mem[0] === 512'bx) begin
            $readmemh("golden_model/input_vectors.txt", input_mem);
        end
        $display("  [LOAD] C:/Users/Purav/Desktop/Major Project/golden_model/input_vectors.txt -> input_mem (Block 0)");

        $readmemh("C:/Users/Purav/Desktop/Major Project/golden_model/final_hashes.txt", expected_final_mem);
        if (expected_final_mem[0] === 256'bx) begin
            $readmemh("../golden_model/final_hashes.txt", expected_final_mem);
        end
        if (expected_final_mem[0] === 256'bx) begin
            $readmemh("final_hashes.txt", expected_final_mem);
        end
        $display("  [LOAD] C:/Users/Purav/Desktop/Major Project/golden_model/final_hashes.txt  -> expected_final_mem (Digest 0)");

        $display("[INFO] Verification memories initialized successfully.");
        $display("================================================================\n");
    end

    // ------------------------------------------------------------------------
    // Verification Sequence
    // ------------------------------------------------------------------------
    integer compress_cycles;

    initial begin
        $dumpfile("tb_sha256_8bit.vcd");
        $dumpvars(0, tb_sha256_8bit);

        rst      = 1'b0;
        valid_in = 1'b0;
        block_in = 512'd0;
        compress_cycles = 0;

        $display("[TIME: %0t ns] Applying synchronous active-high reset...", $time);
        @(posedge clk);
        rst <= 1'b1;
        repeat (5) @(posedge clk);
        rst <= 1'b0;
        $display("[TIME: %0t ns] Reset released. Injecting 512-bit message block...", $time);
        repeat (2) @(posedge clk);

        $display("  Block Data: %0128h", input_mem[0]);
        @(posedge clk);
        block_in <= input_mem[0];
        valid_in <= 1'b1;

        @(posedge clk);
        valid_in <= 1'b0;
        block_in <= 512'd0;

        // Count compression cycles until valid_out assertion
        $display("[TIME: %0t ns] Block injected. Commencing 256-cycle folded compression...", $time);
        @(posedge clk); // STATE_INIT

        while (!valid_out) begin
            @(posedge clk);
            compress_cycles = compress_cycles + 1;
        end

        $display("[TIME: %0t ns] Execution completed in %0d clock cycles!", $time, compress_cycles);

        // Verify digest
        if (hash_out !== expected_final_mem[0]) begin
            $display("\n****************************************************************");
            $display("  [ASSERTION FAILED] Hash Digest Mismatch!");
            $display("  Time     : %0t ns", $time);
            $display("  Expected : 0x%064h", expected_final_mem[0]);
            $display("  Actual   : 0x%064h", hash_out);
            $display("****************************************************************\n");
            $stop;
        end else begin
            $display("\n================================================================");
            $display("                   SIMULATION PASSED");
            $display(" SHA-256 8-Bit Folded Core Verified Successfully!");
            $display(" 256-Cycle COMPRESS Loop Executed Accurately.");
            $display(" Output Digest : %064h", hash_out);
            $display(" Expected      : %064h", expected_final_mem[0]);
            $display("================================================================\n");
        end

        repeat (5) @(posedge clk);
        $finish;
    end

endmodule
